const event = (type, at, extra = {}) => ({type: 'event_msg', timestamp: new Date(at).toISOString(), payload: {type, ...extra}});
test('activity follows task lifecycle, blocking input and stale observations', () => {
  const activity = new ChatActivity();
  activity.accept(event('task_started', 1000));
  assert.equal(activity.displayState(2000), 'running');
  activity.accept({type: 'response_item', timestamp: new Date(2000).toISOString(), payload: {type: 'function_call', name: 'functions.request_user_input', call_id: 'input1'}});
  assert.equal(activity.state, 'waiting');
  activity.accept({type: 'response_item', timestamp: new Date(3000).toISOString(), payload: {type: 'function_call_output', call_id: 'input1'}});
  assert.equal(activity.state, 'running');
  assert.equal(activity.displayState(31 * 60 * 1000), 'uncertain');
  activity.accept(event('task_complete', 4000));
  assert.equal(activity.displayState(31 * 60 * 1000), 'completed');
  activity.accept(event('task_started', 5000));
  activity.accept(event('turn_aborted', 6000));
  assert.equal(activity.state, 'interrupted');
  activity.accept(event('task_started', 7000));
  activity.accept(event('error', 8000));
  assert.equal(activity.state, 'failed');
});
test('a tail without a start marker can recover activity and async questions stay visible until the answer', () => {
  const activity = new ChatActivity();
  activity.accept(event('token_count', 1000));
  activity.accept({type: 'response_item', timestamp: new Date(2000).toISOString(), payload: {type: 'function_call', name: 'functions.request_user_input_async', call_id: 'async1'}});
  assert.equal(activity.state, 'waiting');
  assert.equal(activity.waitingKind, 'question');
  activity.accept({type: 'response_item', timestamp: new Date(2500).toISOString(), payload: {type: 'function_call_output', call_id: 'async1', output: '{"accepted":true}'}});
  assert.equal(activity.state, 'waiting');
  activity.accept({type: 'response_item', timestamp: new Date(3000).toISOString(), payload: {type: 'message', role: 'user', content: [{type: 'input_text', text: '我的选择是 B'}]}});
  assert.equal(activity.state, 'running');
});
test('approval is distinct from questions, resolves independently and end-of-turn clears attention', () => {
  const activity = new ChatActivity();
  activity.accept(event('task_started', 1000));
  activity.accept(event('exec_approval_request', 2000, {id: 'approve1'}));
  assert.equal(activity.waitingKind, 'approval');
  activity.accept(event('exec_approval_response', 3000));
  assert.equal(activity.state, 'running');
  activity.accept(event('request_user_input', 4000));
  assert.equal(activity.waitingKind, 'question');
  activity.accept(event('task_complete', 5000));
  assert.equal(activity.state, 'completed');
  assert.equal(activity.waitingKind, null);
});
test('informational permission hook records no command, never makes a decision and correlates completion', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'niang-hooks-'));t.after(() => fs.rmSync(root, {recursive:true,force:true}));
  const input = {session_id:'00000000-0000-4000-8000-000000000001',turn_id:'turn1',tool_name:'Bash',tool_input:{command:'echo private-value'}};
  assert.equal(recordChatHook({...input,hook_event_name:'PermissionRequest'},root,1000),undefined);
  let records=readApprovalRecords(root);assert.equal(records.length,1);assert.equal(records[0].kind,'approval');
  assert.equal(JSON.stringify(records).includes('private-value'),false);assert.equal(Object.hasOwn(records[0],'decision'),false);
  recordChatHook({...input,tool_input:{command:'echo different'},hook_event_name:'PostToolUse'},root,2000);
  assert.equal(readApprovalRecords(root).length,1);
  recordChatHook({...input,hook_event_name:'PostToolUse'},root,3000);assert.equal(readApprovalRecords(root).length,0);
  recordChatHook({...input,hook_event_name:'PermissionRequest'},root,4000);
  recordChatHook({...input,hook_event_name:'Interrupt'},root,5000);assert.equal(readApprovalRecords(root).length,0);
  recordChatHook({...input,session_id:'../escape',hook_event_name:'PermissionRequest'},root,6000);assert.equal(readApprovalRecords(root).length,0);
});
test('read-only index uses display titles, hides archived and internal threads, follows appends and truncation', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'niang-chats-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  fs.mkdirSync(path.join(root, 'sessions'));
  const file = path.join(root, 'sessions', 'chat.jsonl');
  const now = Date.now();
  fs.writeFileSync(file, JSON.stringify(event('task_started', now - 1000)) + '\n');
  const db = new DatabaseSync(path.join(root, 'state_5.sqlite'));
  db.exec('CREATE TABLE threads(id TEXT,title TEXT,name TEXT,rollout_path TEXT,cwd TEXT,source TEXT,archived INTEGER,updated_at INTEGER);');
  const insert = db.prepare('INSERT INTO threads VALUES(?,?,?,?,?,?,?,?)');
  insert.run('00000000-0000-4000-8000-000000000001', 'Original user message', '实际聊天标题', file, root, 'vscode', 0, Math.floor(now / 1000));
  insert.run('archived', 'old', null, file, root, 'vscode', 1, Math.floor(now / 1000));
  insert.run('guardian', 'internal', null, file, root, '{"subagent":{"other":"guardian"}}', 0, Math.floor(now / 1000));
  db.close();
  const monitor = createChatMonitor(root);
  let snapshot = monitor.snapshot(now);
  assert.equal(snapshot.ok, true);
  assert.equal(snapshot.threads.length, 1);
  assert.equal(snapshot.threads[0].title, '实际聊天标题');
  assert.equal(snapshot.threads[0].state, 'running');
  assert.equal(Object.hasOwn(snapshot.threads[0], 'messages'), false);
  fs.appendFileSync(file, JSON.stringify(event('task_complete', now + 1000)) + '\n');
  assert.equal(monitor.snapshot(now + 2000).threads[0].state, 'completed');
  const tail = new RolloutTail(file, () => new ChatActivity());
  assert.equal(tail.update().state, 'completed');
  fs.writeFileSync(file, JSON.stringify(event('turn_aborted', now)) + '\n');
  assert.equal(tail.update().state, 'interrupted');
  const outside = path.join(root, 'private.jsonl'); fs.writeFileSync(outside, '');
  assert.equal(allowedRollout(outside, root), null);
  assert.equal(allowedRollout(path.toNamespacedPath(file), root), fs.realpathSync.native(file));
});
